import { describe, expect, it } from "vitest";
import {
  partySchema,
  draftSchema,
  canTransition,
  signatureSchema,
} from "../lib/domain";
describe("contract boundaries", () => {
  const party = {
    name: "Test Company",
    address: "Tashkent",
    phone: "+998901234567",
    pinfl: "12345678901234",
    passport: "",
    role: "customer",
  };
  it("accepts PINFL or passport but rejects missing identification", () => {
    expect(partySchema.safeParse(party).success).toBe(true);
    expect(
      partySchema.safeParse({ ...party, pinfl: "", passport: "AA1234567" })
        .success,
    ).toBe(true);
    expect(
      partySchema.safeParse({ ...party, pinfl: "", passport: "" }).success,
    ).toBe(false);
    expect(partySchema.safeParse({ ...party, pinfl: "123" }).success).toBe(
      false,
    );
  });
  it("never reopens closed or cancelled contracts and never skips signing", () => {
    expect(canTransition("Draft", "Closed")).toBe(false);
    expect(canTransition("Sent", "Signed")).toBe(true);
    expect(canTransition("Signed", "Closed")).toBe(true);
    expect(canTransition("Closed", "Draft")).toBe(false);
    expect(canTransition("Cancelled", "Sent")).toBe(false);
  });
  it("rejects executable or excessive editor content", () => {
    expect(
      draftSchema.safeParse({
        title: "Test",
        content: {
          type: "doc",
          content: [{ type: "script", text: "alert(1)" }],
        },
        creator: party,
        recipientRole: "provider",
      }).success,
    ).toBe(false);
  });
  it("rejects arbitrary files presented as signature images", () => {
    expect(
      signatureSchema.safeParse("data:image/svg+xml;base64,PHN2Zz4=").success,
    ).toBe(false);
    expect(
      signatureSchema.safeParse("data:image/png;base64,short").success,
    ).toBe(false);
  });
  it("rejects malformed nested editor values without throwing", () => {
    const base = { title: "Test", creator: party, recipientRole: "customer" };
    for (const node of [
      { type: "text", text: {} },
      { type: "paragraph", marks: {} },
      { type: "heading", attrs: { level: "invalid" } },
      { type: "paragraph", content: "oops" },
    ]) {
      expect(() =>
        draftSchema.safeParse({
          ...base,
          content: { type: "doc", content: [node] },
        }),
      ).not.toThrow();
      expect(
        draftSchema.safeParse({
          ...base,
          content: { type: "doc", content: [node] },
        }).success,
      ).toBe(false);
    }
  });
  it("accepts the ordered-list JSON generated by Tiptap", () => {
    expect(
      draftSchema.safeParse({
        title: "List",
        creator: party,
        recipientRole: "customer",
        content: {
          type: "doc",
          content: [
            {
              type: "orderedList",
              attrs: { start: 1, type: null },
              content: [
                {
                  type: "listItem",
                  content: [
                    {
                      type: "paragraph",
                      content: [{ type: "text", text: "Item" }],
                    },
                  ],
                },
              ],
            },
          ],
        },
      }).success,
    ).toBe(true);
  });
});
